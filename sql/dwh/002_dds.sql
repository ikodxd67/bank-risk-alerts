-- Детальный слой хранилища: измерения и факт операций.

-- Клиент — SCD2: изменение города или сегмента даёт новую версию.
-- Версия живёт в полуинтервале [valid_from, valid_to); открытая — valid_to = 9999-12-31.
-- Первая версия начинается с 1900-01-01: источник хранит только текущее состояние,
-- история до запуска хранилища неизвестна.
CREATE TABLE dim_client (
    client_sk  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    client_id  NUMBER(10)    NOT NULL,
    full_name  VARCHAR2(100) NOT NULL,
    birth_date DATE          NOT NULL,
    city       VARCHAR2(50)  NOT NULL,
    segment    VARCHAR2(10)  NOT NULL,
    valid_from DATE          NOT NULL,
    valid_to   DATE          NOT NULL,
    CONSTRAINT uq_dim_client_version UNIQUE (client_id, valid_from),
    CONSTRAINT ck_dim_client_period CHECK (valid_from < valid_to)
);
/

CREATE INDEX ix_dim_client_open ON dim_client (client_id, valid_to);
/

-- Карты и продавцы не меняются по смыслу — SCD1 (перезапись через MERGE).
CREATE TABLE dim_card (
    card_id   NUMBER(12)   PRIMARY KEY,
    client_id NUMBER(10)   NOT NULL,
    card_type VARCHAR2(10) NOT NULL,
    opened_at DATE         NOT NULL
);
/

CREATE TABLE dim_merchant (
    merchant_id NUMBER(8)     PRIMARY KEY,
    name        VARCHAR2(100) NOT NULL,
    mcc         CHAR(4)       NOT NULL,
    country     CHAR(2)       NOT NULL
);
/

-- Факт операций. Партиция на месяц, новые создаются сами (interval).
-- Первичного ключа нет: глобальный индекс мешал бы обмену партиций;
-- уникальность держит загрузка (DELETE+INSERT дня), проверяют тесты.
-- client_id/client_sk NOT NULL — операция по неизвестной хранилищу карте
-- уронит загрузку, а не потеряется молча в JOIN.
CREATE TABLE fct_transactions (
    trx_id      NUMBER(14)   NOT NULL,
    trx_ts      TIMESTAMP    NOT NULL,
    trx_date    DATE         NOT NULL,
    card_id     NUMBER(12)   NOT NULL,
    client_id   NUMBER(10)   NOT NULL,
    client_sk   NUMBER       NOT NULL,
    merchant_id NUMBER(8),
    amount      NUMBER(14,2) NOT NULL,
    channel     VARCHAR2(6)  NOT NULL,
    country     CHAR(2)      NOT NULL,
    device_id   VARCHAR2(20),
    status      VARCHAR2(8)  NOT NULL,
    loaded_at   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
)
PARTITION BY RANGE (trx_date) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(PARTITION p_start VALUES LESS THAN (DATE '2026-01-01'));
/
